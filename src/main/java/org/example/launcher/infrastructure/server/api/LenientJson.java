package org.example.launcher.infrastructure.server.api;

/**
 * Терпеливая подготовка JSON, написанного человеком вручную.
 *
 * <p>Манифест {@code build.json} администраторы правят в блокноте,
 * и самые частые ошибки — лишняя запятая перед закрывающей скобкой,
 * пропущенная запятая между полями, BOM в начале файла и комментарии.
 * Строгий парсер из-за любой из них отбрасывает весь манифест, и сборка
 * теряет описание, версию и загрузчик. {@link #sanitize} чинит эти
 * ошибки до передачи строки в Gson, не притрагиваясь к корректному
 * JSON.</p>
 */
final class LenientJson {

    private LenientJson() {
    }

    /**
     * @return JSON, очищенный от типичных ошибок ручного редактирования;
     *         корректный JSON возвращается без изменений
     */
    static String sanitize(String json) {
        if (json == null) {
            return null;
        }
        String text = json.strip();
        // BOM в начале файла (блокнот Windows сохраняет его молча)
        while (!text.isEmpty() && text.charAt(0) == '\uFEFF') {
            text = text.substring(1).stripLeading();
        }
        // Строчные и блочные комментарии
        text = text.replaceAll("(?m)^\\s*//.*$", "");
        text = text.replaceAll("(?s)/\\*.*?\\*/", "");
        // Висячая запятая перед } или ]
        text = text.replaceAll(",\\s*([}\\]])", "$1");
        // Пропущенная запятая: строка заканчивает строку файла, а на
        // следующей строке снова начинается строка (в корректном JSON
        // между двумя строками-токенами всегда стоит запятая)
        text = text.replaceAll(
                "(\"(?:[^\"\\\\]|\\\\.)*\"[ \\t]*)\\r?\\n(\\s*\")",
                "$1,$2");
        return text;
    }
}
